import { expect, test } from '@playwright/test'
import type { Snapshot } from '../src/types/world'

test('living world, controls, selection, camera, synchronization and replay', async ({ page, request, context }) => {
  test.setTimeout(300000)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await request.post('/api/simulation/reset', { data: { seed: 42 } })
  await page.goto('/')
  await expect(page.getByText('Connected to simulation')).toBeVisible()
  await expect(page.locator('canvas')).toBeVisible()
  await expect(page.getByText('Preparing your world…')).toHaveCount(0)
  expect(await page.locator('.roster-grid button').count()).toBe(10)
  let before: Snapshot = await (await request.get('/api/world')).json()
  await page.getByRole('button', { name: '▶ Start world' }).click()
  await expect(page.getByRole('button', { name: 'Ⅱ Pause world' })).toBeVisible()
  await page.getByRole('button', { name: '8×', exact: true }).click()
  await expect.poll(async () => (await (await request.get('/api/world')).json()).state.tick).toBeGreaterThanOrEqual(8)
  await page.getByRole('button', { name: 'Ⅱ Pause world' }).click()
  await expect(page.getByRole('button', { name: '▶ Resume world' })).toBeVisible()
  const paused: Snapshot = await (await request.get('/api/world')).json()
  expect(paused.state.agents).not.toEqual(before.state.agents)
  await page.waitForTimeout(200)
  expect((await (await request.get('/api/world')).json()).state.tick).toBe(paused.state.tick)
  await page.getByRole('button', { name: '↦ Advance one tick' }).click()
  await expect.poll(async () => (await (await request.get('/api/world')).json()).state.tick).toBe(paused.state.tick+1)
  await expect(page.locator('.tick>span')).toHaveText(String(paused.state.tick+1).padStart(5,'0'))
  await page.getByRole('button', { name: 'Inspect Ada' }).click()
  await expect(page.locator('.agent-profile h2')).toHaveText('Ada')
  await expect(page.getByText('Higher hunger means closer to starvation.')).toBeVisible()
  await page.getByRole('button', {name:'Vision',exact:true}).click()
  const perception = await (await request.get('/api/agents/agent-00/observation')).json()
  await expect(page.getByRole('heading', {name:`Local vision · ${perception.observation.vision_radius} tiles`})).toBeVisible()
  await expect(page.locator('.inspector-content')).toContainText('Visible terrain')
  await expect(page.locator('.inspector-content')).toContainText('Visible resources')
  await page.getByRole('button', {name:'Overview',exact:true}).click()
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await page.getByRole('button', { name: '⛶ Fit world' }).click()
  await page.waitForTimeout(300)
  const box = await page.locator('canvas').boundingBox()
  expect(box).not.toBeNull()
  if (!box) throw new Error('Canvas has no bounds')
  before = await (await request.get('/api/world')).json()
  const a = before.state.agents['agent-00']
  const bounds = await page.locator('.world-canvas').evaluate(el => ({left:Number((el as HTMLElement).dataset.cameraLeft),top:Number((el as HTMLElement).dataset.cameraTop),right:Number((el as HTMLElement).dataset.cameraRight),bottom:Number((el as HTMLElement).dataset.cameraBottom)}))
  const tileWidth = box.width/(bounds.right-bounds.left), tileHeight=box.height/(bounds.bottom-bounds.top)
  // Click the human's head in the fitted world, exercising Pixi's hit testing.
  await page.mouse.click(box.x+(a.position.x+.5-bounds.left)*tileWidth,
    box.y+(a.position.y+.4-bounds.top)*tileHeight)
  await expect(page.locator('.agent-profile h2')).toHaveText('Ada')
  await page.getByRole('button', {name:'Decision',exact:true}).click()
  expect(await page.locator('.utility-list details').count()).toBeGreaterThanOrEqual(13)
  await page.getByRole('button', {name:'Personality',exact:true}).click()
  await expect(page.locator('.inspector-content .meter')).toHaveCount(10)
  await page.getByRole('button', {name:'Overview',exact:true}).click()
  await expect(page.getByRole('img',{name:'Explored world minimap'})).toBeVisible()
  await page.getByRole('button', {name:'Follow agent',exact:true}).click()
  await expect(page.getByRole('button', {name:'Follow agent',exact:true})).toHaveClass(/chosen/)
  await page.mouse.move(box.x+box.width/2, box.y+box.height/2)
  await page.mouse.wheel(0,-200)
  await page.mouse.down(); await page.mouse.move(box.x+box.width/2+40,box.y+box.height/2+20); await page.mouse.up()
  await page.getByRole('button', { name: '⌖ Center' }).click()
  await page.getByRole('button', { name: '⛶ Fit world' }).click()
  await context.setOffline(true)
  await expect(page.getByText('Reconnecting…')).toBeVisible()
  await context.setOffline(false)
  await expect(page.getByText('Connected to simulation')).toBeVisible({ timeout: 10000 })
  // Observe a full simulation day with the slower hunger clock and real survival policies.
  for (let i = before.state.tick; i < 240; i++) {
    const response = await request.post('/api/simulation/step')
    expect(response.ok()).toBeTruthy()
  }
  const final: Snapshot = await (await request.get('/api/world')).json()
  await expect(page.locator('.tick>span')).toHaveText(String(final.state.tick).padStart(5,'0'))
  const actions = new Set<string>()
  let after = 0
  for (;;) {
    const data = await (await request.get(`/api/events?after=${after}&limit=2000`)).json()
    if (!data.events.length) break
    for (const e of data.events) if (e.event_type === 'ACTION_RESOLVED') actions.add(e.payload.action)
    after = data.next_sequence
  }
  expect([...actions]).toEqual(expect.arrayContaining(['MOVE','GATHER','EAT','REST']))
  const replay = await (await request.get(`/api/replay/${final.run_id}`)).json()
  expect(replay.state_hash).toBe(final.state_hash)
  await page.getByRole('button', {name:'Memory',exact:true}).click()
  await expect(page.getByRole('heading', {name:/Short-term memory/})).toBeVisible()
  await expect(page.getByRole('heading', {name:/Long-term memory/})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Practical lessons'})).toBeVisible()
  const memory=final.state.agents['agent-00'].memory
  expect(memory?.short_term.length).toBeGreaterThan(0)
  expect(memory?.long_term.length).toBeGreaterThan(0)
  expect(Object.keys(memory?.lessons??{}).length).toBeGreaterThan(0)
  await page.screenshot({path:'../artifacts/genesis-memory.png',fullPage:true})
  await page.getByRole('button', {name:'Plans',exact:true}).click()
  await expect(page.getByRole('heading', {name:'Current plan'})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Verified strategies'})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Plan outcomes'})).toBeVisible()
  const planner = Object.values(final.state.agents).find(a=>Object.keys(a.skills??{}).length>0 && (a.task_history?.length??0)>0)
  expect(planner).toBeDefined()
  if (!planner) throw new Error('No agent verified a strategy')
  await page.getByRole('button', {name:`Inspect ${planner.name}`,exact:true}).click()
  await expect(page.locator('.inspector-content')).toContainText('successes')
  await expect(page.locator('.inspector-content .recent-activity')).toContainText('succeeded')
  const engineer = Object.values(final.state.agents).find(a=>(a.housing?.trials.length??0)>0)
  expect(engineer).toBeDefined()
  if (!engineer) throw new Error('No agent completed a shelter trial')
  await page.getByRole('button', {name:`Inspect ${engineer.name}`,exact:true}).click()
  await page.getByRole('button', {name:'Building',exact:true}).click()
  await expect(page.getByRole('heading', {name:'Construction learning'})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Invention workshop'})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Recent tool evidence'})).toBeVisible()
  await expect(page.getByRole('heading', {name:'Tested designs'})).toBeVisible()
  await expect(page.locator('.inspector-content')).toContainText(/Prototype stood|Prototype failed/)
  await page.screenshot({path:'../artifacts/genesis-construction-learning.png',fullPage:true})
  await page.getByRole('button', {name:'Plans',exact:true}).click()
  await page.screenshot({path:'../artifacts/genesis-plans.png',fullPage:true})
  await page.getByRole('button', {name:'Overview',exact:true}).click()
  await page.getByLabel('Filter event type').selectOption('GATHER')
  await expect(page.locator('.event-row').first()).toContainText('gathered')
  // Different agents can spend the day inventing, building or gathering.
  // Filter a gatherer actually present in the journal rather than prescribing Ada's role.
  const gatheringText = await page.locator('.event-row').first().innerText()
  const gatherer = Object.values(final.state.agents).find(a=>gatheringText.includes(`${a.name} gathered`))
  expect(gatherer).toBeDefined()
  if (!gatherer) throw new Error('No visible gatherer in the journal')
  await page.getByLabel('Filter agent').selectOption(gatherer.id)
  await expect(page.locator('.event-row').first()).toContainText(`${gatherer.name} gathered`)
  await page.getByLabel('Filter event type').selectOption('all')
  await page.getByLabel('Filter agent').selectOption('all')
  await page.screenshot({ path: '../artifacts/genesis-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('canvas')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '../artifacts/genesis-mobile.png', fullPage: true })
  await page.getByLabel('World seed').fill('123')
  await page.getByRole('button', { name: '↺ Reset world' }).click()
  await expect(page.locator('.tick>span')).toHaveText('00000')
  const reset = await (await request.get('/api/world')).json()
  expect(reset.state.config.seed).toBe(123)
  expect(reset.run_id).not.toBe(final.run_id)
  await expect(page.locator('.agent-profile')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('signed viewport streaming is independent of simulation and settlement focus works', async ({ page, request }) => {
  await request.post('/api/simulation/reset', {data:{seed:42}})
  const chunks: string[]=[]
  page.on('websocket',socket=>socket.on('framereceived',({payload})=>{
    if(typeof payload !== 'string') return
    const p=JSON.parse(payload)
    if(p.type==='chunks') chunks.push(...p.chunks.map((c:{key:string})=>c.key))
  }))
  await page.goto('/')
  await expect(page.getByText('Connected to simulation')).toBeVisible()
  await expect(page.getByText('Preparing your world…')).toHaveCount(0)
  await expect.poll(()=>chunks.length).toBeGreaterThan(0)
  const before:Snapshot=await (await request.get('/api/world')).json()
  const box=await page.locator('canvas').boundingBox()
  if(!box) throw new Error('Missing world canvas')
  for(let i=0;i<4;i++) {
    await page.mouse.move(box.x+60,box.y+box.height/2)
    await page.mouse.down()
    await page.mouse.move(box.x+box.width-60,box.y+box.height/2,{steps:8})
    await page.mouse.up()
    await page.waitForTimeout(350)
  }
  await expect.poll(()=>chunks.some(key=>Number(key.split(',')[0])<=-2)).toBeTruthy()
  const after:Snapshot=await (await request.get('/api/world')).json()
  expect(after.state_hash).toBe(before.state_hash)
  expect(after.state.explored_chunks).toEqual(before.state.explored_chunks)
  await page.getByRole('button',{name:'⌖ Hearthgrove'}).click()
  await page.waitForTimeout(500)
  await page.locator('.settlement-members button').filter({hasText:'Mira'}).click()
  await expect(page.locator('.agent-profile h2')).toHaveText('Mira')
  await page.getByRole('button',{name:'Decision',exact:true}).click()
  expect(await page.locator('.utility-list details').count()).toBe(0) // No policy tick has occurred.
  await page.getByRole('button',{name:'↦ Advance one tick'}).click()
  await expect.poll(()=>page.locator('.utility-list details').count()).toBeGreaterThanOrEqual(13)
  await page.locator('.utility-list details').first().locator('summary').click()
  await expect(page.locator('.utility-list details[open]')).toBeVisible()
  await page.getByRole('button',{name:'Effects on'}).click()
  await expect(page.getByRole('button',{name:'Effects off'})).toBeVisible()
  await page.locator('.performance summary').click()
  await expect(page.locator('.performance')).toContainText('0 missing assets')
  await page.screenshot({path:'../artifacts/genesis-decisions.png',fullPage:true})
})
